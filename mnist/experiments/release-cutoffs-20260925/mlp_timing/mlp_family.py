"""The MLP family timed against the cutoffs: one harness-ready template, four knobs.

``source(k, width, steps, batch)`` returns the text of a complete popcorn3
submission (it passes the harness's source rules and runs unchanged under
``tools/score_submissions.py``), so the code the sweep times is byte for byte
the code the harness later confirms. It generalises
``popcorn3/submissions/mlp_ensemble.py``:

* K independent 60-W-W-10 ReLU networks held as (K, in, out) stacks and
  trained in one bmm pass, each on its own shuffle of all 10,000 labelled rows;
* dropout 0.1 on hidden units, Gaussian input noise 0.3, label smoothing 0.1;
* AdamW, weight decay 0.01, learning rate 2e-3 x sqrt(batch / 128), 10% linear
  warm-up then cosine to zero over exactly ``steps`` steps (the original rounds
  up to whole epochs; this runs partial epochs, so 25 steps means 25 steps);
* an EMA of the weights for prediction with a horizon of a quarter of the run
  (decay 1 - 4 / steps, which is the original's 0.999 at 4,000 steps),
  bias-corrected; the members' softmax averaged.

Nothing is tuned per cutoff except the four knobs: K, width, steps, batch.
"""

