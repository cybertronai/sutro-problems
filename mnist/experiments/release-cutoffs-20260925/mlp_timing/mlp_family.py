def name(k, width, steps, batch, graphed=False):
    return f"mlp{'g' if graphed else ''}-k{k}-w{width}-s{steps}-b{batch}"


def parse(label):
    """name() inverted: (k, width, steps, batch, graphed)."""
    family, *parts = label.split("-")
    return tuple(int(part[1:]) for part in parts) + (family == "mlpg",)


def source(k, width, steps, batch, graphed=False):
    lr = round(2e-3 * (batch / 128) ** 0.5, 8)
    ema = round(1.0 - 4.0 / steps, 10)
    return (GRAPH_TEMPLATE if graphed else TEMPLATE).format(
        name=name(k, width, steps, batch, graphed), k=k, width=width, steps=steps, batch=batch, lr=lr, ema=ema)


STEPS = [25, 50, 100, 200, 400, 800, 1600, 3200, 6400]
SHAPES = [(k, width, batch) for k in (1, 4, 16) for width in (256, 1024) for batch in (128, 512)]
# Longer and larger runs, to find the best any member of the family does under the
# harness's 60 s per-call limit.
LONG = [(16, 1024, 12800, 128), (16, 1024, 25600, 128), (16, 1024, 12800, 512), (16, 1024, 25600, 512),
        (64, 1024, 3200, 128), (64, 1024, 6400, 128), (64, 1024, 12800, 128),
        (32, 1024, 6400, 256), (32, 1024, 12800, 256), (32, 2048, 6400, 128)]


def grid():
    """Every eager (k, width, steps, batch, False) of the sweep, shortest first within a shape."""
    main = [(k, width, steps, batch, False) for k, width, batch in SHAPES for steps in STEPS]
    return main + [c + (False,) for c in LONG]


def graph_grid():
    """The graph-captured twins: the same shapes and step counts."""
    return [c[:4] + (True,) for c in grid()]
